import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";
import type { GraphEntity, HomeGraph, ResolvedReference } from "./homeGraph.js";

interface SnapshotNode {
  uri: string;
  name: string;
  types: string[];
  resourceIdentifier?: string;
  adapter?: string;
  endpointURL?: string;
  requestParameters?: string;
  unit?: string;
}

interface SnapshotEdge {
  source: string;
  target: string;
  relationshipType: string;
}

const BASE = "https://example.org/regiodeal/resource/";
const ENDPOINT = "local://simulation/timeseries.sqlite";

/**
 * Test-only, minimal projection of a local simulator export, not a Neo4j
 * substitute or an authorization adapter. Nothing is copied or serialized.
 * The explicitly selected directory, never graph metadata, selects the DB.
 */
export async function loadSimulatorSnapshot(directory: string) {
  for (const [file, digest] of [
    ["neo4j.json", "63a07d69b0317c53949e612c4347914e80d5782f82c1179d3f6aa2f37875a5bb"],
    ["timeseries.sqlite", "37510dca058814891b0898c27d9022e04f61bc0f67f3a9425e8014816b6aa0d3"],
  ] as const) {
    const bytes = await readFile(resolve(directory, file));
    assert.equal(createHash("sha256").update(bytes).digest("hex"), digest,
      "Snapshot pair changed; inspect provenance and update the local acceptance fixture deliberately");
  }
  const source = JSON.parse(await readFile(resolve(directory, "SOURCE.json"), "utf8")) as {
    scope: string; simulatorCommit: string; sqlite: string; sqliteEndpoint: string;
  };
  assert.equal(source.scope, "cphs:simulation:couple-apartment", "Unexpected snapshot scope");
  assert.equal(source.simulatorCommit, "3f881eb", "Refresh snapshot provenance before changing the simulator revision");
  assert.equal(source.sqliteEndpoint, ENDPOINT, "Unsupported snapshot endpoint");
  const snapshot = JSON.parse(await readFile(resolve(directory, "neo4j.json"), "utf8")) as {
    nodes: SnapshotNode[]; edges: SnapshotEdge[];
  };
  const nodes = new Map(snapshot.nodes.map((node) => [node.uri, node]));
  const node = (id: string) => {
    const result = nodes.get(id);
    assert.ok(result, "Missing snapshot node");
    return result;
  };
  const targets = (id: string, relation: string) => snapshot.edges
    .filter((edge) => edge.source === id && edge.relationshipType === relation)
    .map((edge) => node(edge.target));
  const one = <T>(values: T[]): T => {
    assert.equal(values.length, 1, "Expected one unambiguous snapshot mapping");
    return values[0]!;
  };
  // This identifier is generated by simulator/main.py, not inferred from a
  // room or the unrelated configured bedroom database reference's name.
  const referenceNode = node(`${BASE}external/simulation/couple-apartment/temp-hum/Temperature`);
  assert.ok(referenceNode.types.some((type) => type.endsWith("/ExternalDataReference")));
  const ownerNode = one(targets(referenceNode.uri, "DATA_FOR_ENTITY"));
  assert.ok(targets(ownerNode.uri, "HAS_EXTERNAL_DATA").some((ref) => ref.uri === referenceNode.uri),
    "Reference ownership must agree in both export directions");
  const roomNode = one(targets(ownerNode.uri, "INSTALLED_IN"));
  assert.ok(roomNode.types.some((type) => type.endsWith("/Space")));
  const service = one(targets(referenceNode.uri, "ACCESSIBLE_THROUGH"));
  assert.equal(service.adapter, "sqlite", "Unsupported snapshot adapter");
  assert.equal(service.endpointURL, ENDPOINT, "Unsupported snapshot service endpoint");
  const parameters = JSON.parse(service.requestParameters!) as { file: string; table: string; reporting: string };
  assert.equal(parameters.file, source.sqlite, "Snapshot graph and source record must identify the same file");
  assert.equal(parameters.table, "readings");
  assert.equal(parameters.reporting, "periodic");
  const capability = one(targets(ownerNode.uri, "MEASURES")
    .filter((item) => item.uri.endsWith("/measurement/Temperature")));
  assert.equal(capability.unit, "degree Celsius");
  const entity = (item: SnapshotNode, kinds: string[]): GraphEntity => ({
    id: item.uri, name: item.name, kinds,
  });
  const room = entity(roomNode, ["Space"]);
  const sensor = entity(ownerNode, ["Sensor"]);
  const reference: ResolvedReference = {
    id: referenceNode.uri, name: referenceNode.name,
    resource: referenceNode.resourceIdentifier, adapter: service.adapter,
    endpoint: service.endpointURL, reporting: parameters.reporting,
    capabilities: [{ id: capability.uri, unit: capability.unit }],
  };
  assert.ok(reference.resource, "Missing generated series resource");
  const file = resolve(directory, "timeseries.sqlite");
  // Independent source oracle: never use the reader under test to obtain
  // expected evidence. Select no agenda, message or household record.
  const database = new DatabaseSync(file, { readOnly: true });
  let observation: { value: number; observedAt: string };
  try {
    const row = database.prepare(
      "SELECT timestamp, value, sensor, property, event_type FROM readings WHERE series = ? ORDER BY timestamp DESC LIMIT 1",
    ).get(reference.resource) as {
      timestamp: string; value: number; sensor: string; property: string; event_type: string;
    } | undefined;
    assert.ok(row, "Generated temperature series must contain an actual observation");
    assert.equal(`${BASE}${row.sensor}`, ownerNode.uri, "Reading and graph owners must agree");
    assert.equal(row.property, "Temperature");
    assert.equal(row.event_type, "measurement");
    assert.equal(row.timestamp, "2026-10-19T23:59:00+02:00", "Refresh fixed clocks for a different snapshot");
    assert.ok(Number.isFinite(row.value), "Snapshot observation must be numeric");
    observation = { value: row.value, observedAt: row.timestamp };
  } finally {
    database.close();
  }
  const graph: HomeGraph = {
    async findEntities(input) {
      return input.query === room.name && input.kind === "room"
        ? { status: "ok", candidates: [room], truncated: false }
        : { status: "not_found" };
    },
    async inspectNeighborhood(input) {
      if (input.entityIds.length !== 1 || input.entityIds[0] !== room.id) {
        return { status: "not_found", notFound: [...input.entityIds] };
      }
      return {
        status: "ok", entities: [room, sensor],
        relationships: [{ from: sensor.id, type: "INSTALLED_IN", to: room.id }],
        externalData: [{ id: reference.id, name: reference.name, ownerIds: [sensor.id], readable: true }],
        notFound: [], truncated: false,
      };
    },
    async resolveReference(id) {
      return id === reference.id ? { status: "ok", reference } : { status: "not_found" };
    },
    async close() {},
  };
  return { graph, room, sensor, reference, observation, file, unit: capability.unit };
}
